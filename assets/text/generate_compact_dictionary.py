"""One-time deterministic packer; Rust runtime never executes this script.

Keep both original JSON tables as provenance and independent full-dictionary oracles.
All integers are little endian; records are decoded bytewise by Rust (no alignment ABI).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parent
BASE, LIMIT = 0x4E00, 0xA000
HEADER_SIZE = 44
MAGIC = b"CWPDIC1\0"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate(check: bool) -> dict:
    sources = {name: (ROOT / name).read_bytes()
               for name in ("pinyin_chars.json", "pinyin_phrases.json")}
    chars, phrases = (json.loads(sources[name]) for name in sources)
    assert set(chars) == set(map(chr, range(BASE, LIMIT)))
    assert len(chars) == 20992 and len(phrases) == 47111
    assert all(len(parts) == 3 for rows in (chars, phrases)
               for pron in rows.values() for parts in pron)
    assert all(len(pron) <= 1 for pron in chars.values())
    assert all(BASE <= ord(word[0]) < LIMIT and len(word) == len(pron)
               for word, pron in phrases.items())
    tables = [sorted({parts[i] for rows in (chars, phrases)
                      for pron in rows.values() for parts in pron}) for i in range(3)]
    assert all(len(table) < 255 for table in tables)
    ids = [{value: i for i, value in enumerate(table)} for table in tables]

    def encode(pron: list[list[str]]) -> bytes:
        return bytes(ids[i][part] for syllable in pron for i, part in enumerate(syllable))

    char_data = b"".join(encode(chars[chr(cp)]) or b"\xff\xff\xff"
                         for cp in range(BASE, LIMIT))
    ordered = sorted(phrases.items(), key=lambda row: (ord(row[0][0]), -len(row[0]), row[0]))
    records, words, pronunciations, ranges = bytearray(), bytearray(), bytearray(), []
    index = 0
    for cp in range(BASE, LIMIT):
        ranges.append(index)
        while index < len(ordered) and ord(ordered[index][0][0]) == cp:
            word, pron = ordered[index]
            utf8 = word.encode("utf-8")
            assert len(utf8) <= 255 and len(word) <= 255
            records.extend(struct.pack("<IBBI", len(words), len(utf8), len(word), len(pronunciations)))
            words.extend(utf8)
            pronunciations.extend(encode(pron))
            index += 1
    ranges.append(index)
    assert index == len(ordered)
    range_data = struct.pack(f"<{len(ranges)}I", *ranges)
    char_offset = HEADER_SIZE
    range_offset = char_offset + len(char_data)
    record_offset = range_offset + len(range_data)
    word_offset = record_offset + len(records)
    pron_offset = word_offset + len(words)
    total = pron_offset + len(pronunciations)
    header = MAGIC + struct.pack("<9I", BASE, len(chars), len(phrases), char_offset,
                                 range_offset, record_offset, word_offset, pron_offset, total)
    data = header + char_data + range_data + records + words + pronunciations
    assert len(data) == total

    # Decode every syllable and every ordered word independently from packed bytes.
    def decode(blob: bytes) -> list[list[str]]:
        assert len(blob) % 3 == 0
        return [[tables[i][blob[j+i]] for i in range(3)] for j in range(0, len(blob), 3)]

    decoded_chars = 0
    for cp in range(BASE, LIMIT):
        off = char_offset + 3 * (cp - BASE)
        blob = data[off:off+3]
        decoded = [] if blob == b"\xff\xff\xff" else decode(blob)
        assert decoded == chars[chr(cp)], hex(cp)
        decoded_chars += len(decoded)
    decoded_phrases = 0
    for row, (expected_word, expected_pron) in enumerate(ordered):
        off, byte_len, char_len, pron_off = struct.unpack_from("<IBBI", data, record_offset+10*row)
        word = data[word_offset+off:word_offset+off+byte_len].decode("utf-8")
        assert word == expected_word and len(word) == char_len
        pron = decode(data[pron_offset+pron_off:pron_offset+pron_off+char_len*3])
        assert pron == expected_pron, word
        decoded_phrases += len(pron)
    oracle_groups: dict[int, list] = {}
    for word, pron in phrases.items():
        oracle_groups.setdefault(ord(word[0]), []).append((word, pron))
    for cp in range(BASE, LIMIT):
        a, b = ranges[cp-BASE:cp-BASE+2]
        expected = sorted(oracle_groups.get(cp, []), key=lambda row: (-len(row[0]), row[0]))
        assert ordered[a:b] == expected

    meta = "// Generated by generate_compact_dictionary.py; do not hand edit.\n"
    for name, table in zip(("INITIALS", "FINALS", "TONES"), tables):
        meta += f"pub(super) const {name}: [&str; {len(table)}] = " + json.dumps(table, ensure_ascii=False) + ";\n"
    meta_bytes = meta.encode("utf-8")
    outputs = {"pinyin_compact.bin": data, "pinyin_compact_meta.rs": meta_bytes}
    for name, content in outputs.items():
        if check:
            assert (ROOT / name).read_bytes() == content, f"stale generated asset: {name}"
        else:
            (ROOT / name).write_bytes(content)
    receipt = {
        "format": "CWPDIC1 little-endian fixed byte records; zero Rust dictionary heap",
        "chars": len(chars), "empty_char_entries": len(chars)-decoded_chars,
        "phrases": len(phrases), "char_syllables": decoded_chars,
        "phrase_syllables": decoded_phrases, "total_syllables": decoded_chars+decoded_phrases,
        "interned_part_counts": list(map(len, tables)), "binary_bytes": len(data),
        "char_syllables_exact": True, "phrase_syllables_exact": True,
        "all_first_char_group_orders_exact": True,
        "order": "first char codepoint, character length descending, Unicode word ascending",
        "source_sha256": {name: sha(content) for name, content in sources.items()},
        "output_sha256": {name: sha(content) for name, content in outputs.items()},
        "python_required_at_rust_runtime": False,
    }
    if not check:
        (ROOT / "compact_dictionary_receipt.json").write_text(
            json.dumps(receipt, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify deterministic assets without writing")
    print(json.dumps(generate(parser.parse_args().check), ensure_ascii=False, indent=2))
