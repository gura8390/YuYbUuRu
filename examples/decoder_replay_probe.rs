#[derive(Parser, Clone, Debug)]
struct Args {
    #[arg(long)]
    app_dir: PathBuf,
    #[arg(long, value_enum)]
    backend: GpuBackend,
    /// Complete prompt, little-endian float32: raw [N,1024] or C-order NPY.
    #[arg(long)]
    prefill_f32: PathBuf,
    /// External JSON array of i32 token IDs; never generated by this probe.
    #[arg(long)]
    tokens_json: PathBuf,
    #[arg(long, default_value_t=5, value_parser=clap::value_parser!(u32).range(1..=1000))]
    repeats: u32,
    /// Only the two comparison capacities are accepted.
    #[arg(long, default_value_t = 2048)]
    n_ctx: u32,
    /// Use the private one-output-row ASR reservation contract.
    #[arg(long, default_value_t = false)]
    single_output: bool,
    /// Deadline for the single owned native child, including all repeats.
    #[arg(long, default_value_t=300, value_parser=clap::value_parser!(u64).range(1..=3600))]
    timeout_seconds: u64,
    #[arg(long)]
    output: PathBuf,
}

fn hash(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}
fn hash_file(path: &Path) -> Result<String> {
    let mut file = File::open(path)?;
    let mut digest = Sha256::new();
    let mut buffer = [0u8; 65536];
    loop {
        let count = file.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        digest.update(&buffer[..count]);
    }
    Ok(format!("{:x}", digest.finalize()))
}
fn save(path: &Path, report: &Value) -> Result<()> {
    fs::write(path, serde_json::to_vec_pretty(report)?)?;
    Ok(())
}

fn prompt(bytes: &[u8]) -> Result<(Vec<f32>, usize, Value)> {
    let (payload, format, shape) = if bytes.starts_with(b"\x93NUMPY") {
        ensure!(bytes.len() >= 10, "Truncated NPY prefix");
        let (prefix, header_length) = match (bytes[6], bytes[7]) {
            (1, 0) => (
                10usize,
                u16::from_le_bytes(bytes[8..10].try_into()?) as usize,
            ),
            (2 | 3, 0) => {
                ensure!(bytes.len() >= 12, "Truncated NPY v2/v3 prefix");
                (
                    12usize,
                    u32::from_le_bytes(bytes[8..12].try_into()?) as usize,
                )
            }
            version => bail!("Unsupported NPY version {version:?}"),
        };
        ensure!(header_length <= 1024 * 1024, "Unexpected NPY header size");
        let end = prefix
            .checked_add(header_length)
            .context("NPY header overflow")?;
        ensure!(end <= bytes.len(), "Truncated NPY header");
        let header = std::str::from_utf8(&bytes[prefix..end])?;
        ensure!(header.ends_with('\n'), "NPY header must end in newline");
        let dtype_re = Regex::new(r#"['"]descr['"]\s*:\s*['"]([^'"]+)['"]"#)?;
        let dtype = dtype_re.captures(header).context("NPY dtype missing")?;
        ensure!(
            dtype_re.captures_iter(header).count() == 1,
            "Duplicate NPY dtype"
        );
        ensure!(
            &dtype[1] == "<f4" || (&dtype[1] == "=f4" && cfg!(target_endian = "little")),
            "NPY must contain little-endian float32"
        );
        let order_re = Regex::new(r#"['"]fortran_order['"]\s*:\s*(True|False)"#)?;
        let order = order_re
            .captures(header)
            .context("NPY storage order missing")?;
        ensure!(
            order_re.captures_iter(header).count() == 1 && &order[1] == "False",
            "NPY must be C-order"
        );
        let shape_re = Regex::new(r#"['"]shape['"]\s*:\s*\(([^)]*)\)"#)?;
        let dimensions = shape_re.captures(header).context("NPY shape missing")?;
        ensure!(
            shape_re.captures_iter(header).count() == 1,
            "Duplicate NPY shape"
        );
        let shape = dimensions[1]
            .split(',')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(str::parse::<usize>)
            .collect::<std::result::Result<Vec<_>, _>>()?;
        let rows = match shape.as_slice() {
            [rows, 1024] | [1, rows, 1024] => *rows,
            _ => bail!("NPY prompt shape must be [N,1024] or [1,N,1024], found {shape:?}"),
        };
        let expected = rows
            .checked_mul(1024)
            .and_then(|n| n.checked_mul(4))
            .context("NPY shape overflow")?;
        ensure!(
            bytes.len() - end == expected,
            "NPY payload length differs from shape"
        );
        (&bytes[end..], "npy", shape)
    } else {
        ensure!(
            bytes.len() % (1024 * 4) == 0,
            "Raw prompt has an incomplete 1024-float row"
        );
        (bytes, "raw-le-f32", vec![bytes.len() / (1024 * 4), 1024])
    };
    ensure!(!payload.is_empty(), "Prompt must not be empty");
    let values = payload
        .chunks_exact(4)
        .map(|b| f32::from_le_bytes(b.try_into().unwrap()))
        .collect::<Vec<_>>();
    ensure!(
        values.iter().all(|v| v.is_finite()),
        "Prompt contains nonfinite floats"
    );
    let rows = values.len() / 1024;
    Ok((
        values,
        rows,
        json!({"format":format,"shape":shape,"rows":rows,"dimension":1024,
        "container_sha256":hash(bytes),"payload_sha256":hash(payload),"all_finite":true}),
    ))
}

fn snapshot(ctx: &NativeContext, row: usize, width: usize, label: &str) -> Result<Value> {
    let values = ctx.timestamp_logits_copy(row, width)?;
    ensure!(
        values.len() == width && values.iter().all(|v| v.is_finite()),
        "Nonfinite/incomplete logits at {label}"
    );
    let mut digest = Sha256::new();
    let (mut low, mut high) = (f32::INFINITY, f32::NEG_INFINITY);
    for value in values {
        digest.update(value.to_le_bytes());
        low = low.min(value);
        high = high.max(value);
    }
    Ok(
        json!({"label":label,"batch_token_index":row,"count":width,"all_finite":true,
              "min":low,"max":high,"sha256":format!("{:x}",digest.finalize())}),
    )
}

fn run(args: &Args, report: &mut Value) -> Result<()> {
    ensure!(
        matches!(args.n_ctx, 2048 | 4096),
        "--n-ctx must be 2048 or 4096"
    );
    ensure!(
        fs::metadata(&args.prefill_f32)?.len() <= u64::from(args.n_ctx) * 1024 * 4 + 1024 * 1024,
        "Prompt file exceeds the selected context plus bounded NPY header"
    );
    ensure!(
        fs::metadata(&args.tokens_json)?.len() <= 1024 * 1024,
        "Token JSON is unexpectedly large"
    );
    let prompt_bytes = fs::read(&args.prefill_f32)?;
    let (embeddings, rows, prompt_identity) = prompt(&prompt_bytes)?;
    let token_bytes = fs::read(&args.tokens_json)?;
    let tokens: Vec<i32> = serde_json::from_slice(&token_bytes)
        .context("--tokens-json must be a JSON array of i32")?;
    ensure!(!tokens.is_empty(), "Token workload must not be empty");
    ensure!(
        tokens.iter().all(|&id| id >= 0),
        "Token IDs must be nonnegative"
    );
    ensure!(
        rows.checked_add(tokens.len())
            .context("Replay length overflow")?
            <= args.n_ctx as usize,
        "Prompt plus external tokens exceeds selected context"
    );
    report["input"] = json!({"prompt":prompt_identity,"tokens_file_sha256":hash(&token_bytes),
        "token_ids_sha256":hash(&serde_json::to_vec(&tokens)?),"token_count":tokens.len(),
        "token_ids_source":"external JSON; no sampler or expected-output generation"});
    save(&args.output, report)?;
    let dll_dir = args.app_dir.join("core/server/engines/llama/bin");
    let model_path = args
        .app_dir
        .join("models/Qwen3-ASR/Qwen3-ASR-0.6B/qwen3_asr_llm.q4_k.gguf");
    report["model_sha256"] = json!(hash_file(&model_path)?);
    let loaded = Instant::now();
    let model = NativeModel::load_with_backend(&dll_dir, &model_path, true, args.backend)?;
    ensure!(
        model.dim == 1024,
        "Replay expects model embedding dimension1024"
    );
    let vocab = model.vocab_size()?;
    ensure!(
        vocab > 0 && tokens.iter().all(|&id| id < vocab),
        "External token is outside model vocabulary"
    );
    // Encoder .embedding.f32 outputs have the same column count but are not a
    // complete ASR prompt. Validate its boundary token rows from the actual
    // unchanged GGUF; do not silently benchmark the wrong input workload.
    let table = gguf::EmbeddingTable::open(&model_path, model.api.clone())?;
    ensure!(
        table.dim == model.dim,
        "GGUF embedding-table dimension differs from native model"
    );
    let first_id = model.token_id("<|im_start|>")?;
    let last_id = model.token_id("<asr_text>")?;
    let first = table.rows(&[first_id])?;
    let last = table.rows(&[last_id])?;
    ensure!(
        embeddings[..1024]
            .iter()
            .zip(&first)
            .all(|(a, b)| a.to_bits() == b.to_bits())
            && embeddings[(rows - 1) * 1024..]
                .iter()
                .zip(&last)
                .all(|(a, b)| a.to_bits() == b.to_bits()),
        "Input is not a complete ASR prompt: expected GGUF im_start/asr_text boundary rows; encoder-only output must first be wrapped"
    );
    drop(table);
    report["input"]["prompt_boundary_rows_verified"] = json!(true);
    report["vocabulary_size"] = json!(vocab);
    report["model_load_seconds"] = json!(loaded.elapsed().as_secs_f64());
    let initialized = Instant::now();
    // These match the normal ASR wrapper: requested batch4096, ubatch512,
    // full logits, one sequence, FlashAttention and both CPU thread counts1.
    let mut ctx = NativeContext::new_asr(&model, args.n_ctx, 4096, 1, 1, args.single_output)?;
    report["context_seconds"] = json!(initialized.elapsed().as_secs_f64());
    report["parameters"] = json!({"n_ctx":args.n_ctx,"requested_n_batch":4096,
        "effective_n_batch":args.n_ctx.min(4096),"n_ubatch":512,"threads":1,"batch_threads":1,
        "single_output":args.single_output,
        "synchronization":"llama_get_logits_ith via one-float diagnostic copy after every decode",
        "positions":"production prefill MRoPE layout; decode_token uses original automatic KV continuation",
        "finite_scans_timed":false,"sampler_called":false});
    save(&args.output, report)?;
    for repeat in 0..args.repeats {
        let clear_started = Instant::now();
        ctx.clear()?; // Once per repeat; production first/full-clear policy is preserved.
        let clear_seconds = clear_started.elapsed().as_secs_f64();
        let started = Instant::now();
        ctx.prefill(&embeddings, rows, 1024, &[])?;
        let prefill_return_seconds = started.elapsed().as_secs_f64();
        let value = ctx.timestamp_logits_copy(rows - 1, 1)?;
        let prefill_seconds = started.elapsed().as_secs_f64();
        ensure!(value[0].is_finite(), "Nonfinite prefill completion value");
        let mut checkpoints = vec![snapshot(&ctx, rows - 1, vocab as usize, "prefill_last")?];
        let wall = Instant::now();
        let mut token_seconds = Vec::with_capacity(tokens.len());
        for (index, &token) in tokens.iter().enumerate() {
            let started = Instant::now();
            let status = ctx.decode_token(token)?;
            ensure!(
                status == 0,
                "Replay decode failed at token{index}, status{status}"
            );
            // Production sampling synchronizes on this same getter. Keeping a
            // getter per token avoids timing asynchronous submissions alone.
            let value = ctx.timestamp_logits_copy(0, 1)?;
            token_seconds.push(started.elapsed().as_secs_f64());
            ensure!(value[0].is_finite(), "Nonfinite completion at token{index}");
            if index == 0 || (index + 1) % 512 == 0 || index + 1 == tokens.len() {
                checkpoints.push(snapshot(
                    &ctx,
                    0,
                    vocab as usize,
                    &format!("decode_after_{}", index + 1),
                )?);
            }
        }
        let generation_loop_wall_seconds = wall.elapsed().as_secs_f64();
        let generation_seconds: f64 = token_seconds.iter().sum();
        ensure!(generation_seconds > 0.0, "Invalid replay timer");
        report["rounds"].as_array_mut().unwrap().push(json!({"repeat":repeat,
            "clear_seconds":clear_seconds,"prefill_return_seconds":prefill_return_seconds,
            "prefill_seconds":prefill_seconds,"decoded_tokens":tokens.len(),
            "generation_seconds":generation_seconds,"generation_loop_wall_seconds":generation_loop_wall_seconds,
            "tokens_per_second":tokens.len() as f64/generation_seconds,"token_seconds":token_seconds,
            "finite_checkpoints":checkpoints}));
        save(&args.output, report)?;
    }
    report["complete"] = json!(true);
    Ok(())
}

fn child(args: &Args) -> Result<()> {
    let mut report = json!({"schema":1,"complete":false,"backend":args.backend,"repeats":args.repeats,
        "rounds":[],"error":null,"quality_equivalence":"not evaluated",
        "scope":"Fixed external prompt/token decoder replay; timings exclude encoder, token selection and full-vocabulary validation scans"});
    let outcome = run(args, &mut report);
    report["error"] = json!(outcome.as_ref().err().map(|e| format!("{e:#}")));
    save(&args.output, &report)?;
    outcome
}

fn main() -> Result<()> {
    let args = Args::parse();
    if std::env::var_os("YYUR_DECODER_REPLAY_CHILD").is_some() {
        return child(&args);
    }
    ensure!(
        matches!(args.n_ctx, 2048 | 4096),
        "--n-ctx must be2048 or4096"
    );
    if let Some(parent) = args.output.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    let log_path = args.output.with_extension("native.stderr.txt");
    let _reservation = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&args.output)
        .context("Refusing to replace an existing output report")?;
    save(
        &args.output,
        &json!({"schema":1,"complete":false,"error":"child not completed","quality_equivalence":"not evaluated"}),
    )?;
    let log = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&log_path)
        .context("Refusing to replace an existing native log")?;
    let native_bin = args.app_dir.join("core/server/engines/llama/bin");
    let old_path = std::env::var_os("PATH").unwrap_or_default();
    let path = std::env::join_paths(
        std::iter::once(native_bin.clone()).chain(std::env::split_paths(&old_path)),
    )?;
    let mut command = Command::new(std::env::current_exe()?);
    command
        .args(std::env::args_os().skip(1))
        .env("YYUR_DECODER_REPLAY_CHILD", "1")
        .env("PATH", path)
        .stderr(Stdio::from(log));
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        command.creation_flags(0x08000000);
    }
    let mut child = command.spawn().context("Start isolated replay child")?;
    let child_pid = child.id();
    let started = Instant::now();
    let mut timed_out = false;
    let status = loop {
        if let Some(status) = child.try_wait().context("Poll owned replay child")? {
            break status;
        }
        if started.elapsed().as_secs() >= args.timeout_seconds {
            timed_out = true;
            child.kill().context("Stop timed-out owned replay child")?;
            break child.wait().context("Reap timed-out owned replay child")?;
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    };
    let log_bytes = fs::read(&log_path)?;
    let text = String::from_utf8_lossy(&log_bytes);
    let device = match args.backend {
        GpuBackend::Cuda => "CUDA0",
        GpuBackend::Vulkan => "Vulkan0",
    };
    let assignments = Regex::new(r"load_tensors: layer\s+\d+ assigned to device ([^,\s]+)")?
        .captures_iter(&text)
        .map(|c| c[1].to_owned())
        .collect::<Vec<_>>();
    let offload = Regex::new(r"offloaded (\d+)/(\d+) layers to GPU")?;
    let counts = offload.captures(&text).map(|c| {
        (
            c[1].parse::<usize>().unwrap_or(0),
            c[2].parse::<usize>().unwrap_or(0),
        )
    });
    let all_layers = counts.is_some_and(|(a, b)| a > 0 && a == b)
        && !assignments.is_empty()
        && assignments.iter().all(|value| value == device);
    let verified = all_layers && text.contains(&format!("YYUR_GPU_BACKEND {device}"));
    let mut report: Value = serde_json::from_slice(&fs::read(&args.output)?)?;
    report["launcher"] = json!({"owned_child_pid":child_pid,"timed_out":timed_out,
        "timeout_seconds":args.timeout_seconds,"exit_code":status.code(),"child_waited":true});
    report["native_log"] = json!({"path":log_path,"sha256":hash(&log_bytes),"preserved":true});
    report["backend_evidence"] = json!({"device":device,"offloaded_layers":counts.map(|v|v.0),
        "total_layers":counts.map(|v|v.1),"layer_assignment_count":assignments.len(),"verified":verified,
        "child_native_path_prefix":native_bin});
    report["technical_validation_passed"] =
        json!(status.success() && verified && report["complete"] == true);
    save(&args.output, &report)?;
    ensure!(
        status.success(),
        "Replay child failed; inspect {}",
        log_path.display()
    );
    ensure!(
        verified,
        "Actual requested GPU layer assignment was not established by the native log"
    );
    println!("{}", args.output.display());
    Ok(())
}
